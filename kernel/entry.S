# ============================================================================
# lab1 · entry.S —— 内核入口：从上电到"能调用 C 函数"
# ============================================================================
# 【这一刻的处境】
#   QEMU 以 -bios none 启动：复位后 PC = 0x1000（QEMU 自带的一小段 boot ROM），
#   这段 ROM 把你的内核映像加载到 0x80000000，然后跳过去。
#   所以 _entry 的第一条指令落在 0x80000000 —— 这正是 kernel/kernel.ld 里
#   BASE_ADDRESS 的来历。
#
#   此刻的状态：M 态、中断使能不确定、sp 未初始化、没有任何 C 运行环境
#   （没有栈、没有 .bss 清零、没有全局变量可用）。
#
# 【本文件的唯一任务】
#   把 CPU 收拾到"可以安全执行第一条 C 语句"的状态，然后交给 start()。
#   就三件事：关中断 → 从核 park → 给主核设好栈。
#
# 【验收会逐行问你】每条指令为什么在这里。注释里都写了理由。
# ============================================================================

# 用宏而不是硬编码 4096 —— 让"栈大小"只有一个来源(course_sid.h)，
# 和 start.c 里 stack0 的数组长度天然一致。
#include "course_sid.h"

.section .text
.globl _entry

_entry:

        # ---- ① 关中断 ----------------------------------------------------
        # 为什么第一步是这个？因为接下来要连续配置若干 M 态寄存器
        # (mstatus / mepc / PMP)，中途若被中断打断，中断处理程序看到的
        # 是一个"配置到一半"的状态，会做出错误判断。
        #
        # 两条指令合起来才是彻底关：
        #   csrw mie, zero   —— 清空 M 态中断使能寄存器(mie)。
        #                       RISC-V 里"M 态能不能响应某个中断"要
        #                       mstatus.MIE 和 mie 里对应位【同时】为 1。
        #                       把 mie 清 0，等于把所有 M 态中断源一次关掉。
        #   csrci mstatus, 8 —— 清 mstatus 的 bit3 (MIE)，即 M 态总中断开关。
        #                       8 = 1<<3。
        # 只用其中一条也能work，但两条一起语义最完整，答辩好讲。
        csrw mie, zero
        csrci mstatus, 8

        # ---- ② 从核 park --------------------------------------------------
        # 所有 hart(CPU 核)复位后【都会】跳到 _entry，不是只有 hart 0。
        # lab1 只用 hart 0 干活，其它核必须原地自旋：
        #   否则它们会带着未初始化的 sp 一路冲进 start()，
        #   多个核共用/踩踏同一个栈 —— 现象是随机崩溃，极难查。
        #
        # 注意顺序：这一步【必须在设栈之前】做，因为自旋循环本身不用栈，
        # 不需要 sp；反过来先设栈再 park 的话，多个核会先后把同一个
        # stack0 写坏。
        # 用 wfi(Wait For Interrupt) 而不是纯 j 忙等：让核真正挂起，
        # 不白烧 CPU 周期。
        csrr t0, mhartid                # t0 = 当前 hart 编号
        bnez t0, park                   # 不是 hart 0 → 去自旋

        # ---- ③ 给 hart 0 设置内核栈 ---------------------------------------
        # stack0 是 start.c 里声明的数组：char stack0[LAB1_STACK_KB * 1024]
        # 这里只取它的地址，不分配内存 —— 内存是链接器在 .bss 里划好的。
        #
        # 【关键】RISC-V 的栈向【低地址】增长，sp 必须指向数组【末尾之后】
        # 也就是"栈顶"。压栈时 sp 先减再写，正好落进数组范围内。
        # 如果 sp 指向数组开头，第一次压栈就写到数组外面去了。
        #
        # ★ 验收定位题会问："sp 初值与哪个文件的配置必须强一致？"
        #   答：与 start.c 中 stack0 的数组长度、以及 course_sid.h 的
        #       LAB1_STACK_KB 强一致。三者不一致 = 栈溢出踩内存。
        la sp, stack0                   # sp = &stack0[0]
        li t0, LAB1_STACK_KB * 1024     # t0 = 4 * 1024 = 4096
        add sp, sp, t0                  # sp = stack0 + 4096  ← 栈顶

        # ---- ④ 交给 C -----------------------------------------------------
        # 此刻 sp 已就位，可以安全调用 C 函数了。
        # start() 在 start.c，负责 M→S 的特权级切换（含 PMP 配置）。
        # call 将返回地址写入 ra；被调用的 C 函数需要有效栈，
        # 所以必须先设置 sp。
        call start

        # start() 正常情况【不应该返回】—— 它最后执行 mret 跳进 S 态，
        # 永不回头。如果真回到这里，说明 start() 出了问题。
        # 兜底：掉进 park 自旋，而不是继续往下执行未知内存。

# ---- 从核自旋等待 ---------------------------------------------------------
# 所有非 0 号 hart 停在这里。wfi 在无中断时挂起该核。
park:
        wfi
        j park

# ============================================================================
# 陷阱向量（Trap Vector）
# ============================================================================
# 【为什么有这个标号】
# 骨架注释里的"环境注意事项 2"要求：entry.S 的陷阱向量标号前必须加
# .balign 4。原因是 RISC-V 规定 mtvec 写入的地址低 2 位是【模式标志位】，
# 所以基址必须 4 字节对齐；标号若落在未对齐地址，QEMU 会【静默丢弃】
# 整次 csrw mtvec 写入 —— 之后任何异常都会跳到地址 0，现象是莫名死机，
# 极难定位。（这条同样适用于 stvec。）
#
# 【lab1 到底需不需要它？】
# lab1 不使能任何中断，也没有页表(不会缺页)，正常情况下【不会】产生异常，
# 所以这个向量是"防御性"的。但它成本极低，而且骨架注释点名要求，
# 所以保留。start.c 里会用 csrw mtvec 把它装上。
#
# 如果你在设计笔记里论证 lab1 不需要、并决定删掉，
# 那也【必须】把 start.c 里对应的 mtvec 配置一起删掉，两者要一致。
# ============================================================================

.balign 4                               # ★ 4 字节对齐，见上面的说明
.globl mtrapvec
mtrapvec:
        # 最小实现：原地自旋。
        # 真实的内核会在这里保存现场、判断异常原因、打印诊断。
        # lab1 阶段还没有可用的 printf，也无法安全地做任何事
        # （连栈状态都不一定可信），所以最诚实的做法就是停住。
        # 调试技巧：用 QEMU 的 -d int 看 cause，比盯着屏幕猜有效得多。
        j mtrapvec
